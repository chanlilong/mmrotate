"""Regenerate (or ``--check``) the frozen config snapshots in ``tests/frozen_configs``."""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from mmengine.config import Config

from mmrotate.testing.frozen_configs import (
    CONFIG_ROOT,
    FROZEN_ROOT,
    FULL,
    REPO_ROOT,
    SNAPSHOTS,
    snapshot,
)


def _render(rel: str) -> str:
    data = snapshot(Config.fromfile(CONFIG_ROOT / rel), rel in FULL)
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'cfg.yaml'
        Config(data).dump(str(out))
        body = out.read_text()
    header = (
        f'# Frozen snapshot of configs/{rel} for the tests (fully resolved, no _base_).\n'
        '# Generated by `python -m mmrotate.testing.frozen_configs`; do not edit by hand.\n'
    )
    return header + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='only report stale snapshots')
    args = parser.parse_args(argv)
    stale = []
    for rel in SNAPSHOTS:
        if not (CONFIG_ROOT / rel).is_file():
            print(f'skip (no configs/{rel})')
            continue
        dst = (FROZEN_ROOT / rel).with_suffix('.yaml')
        text = _render(rel)
        if dst.is_file() and dst.read_text() == text:
            continue
        stale.append(rel)
        if not args.check:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
            print(f'wrote {dst.relative_to(REPO_ROOT)}')
    if args.check and stale:
        print('stale snapshots:\n  ' + '\n  '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
